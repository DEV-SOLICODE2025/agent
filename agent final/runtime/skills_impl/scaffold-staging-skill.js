const fs = require('fs');
const path = require('path');

function nowStamp() { return new Date().toISOString().replace(/[:.]/g, '-'); }

exports.execute = async function(inputs) {
  // inputs:
  //  - project_name (required)
  //  - allow_write (boolean) -> when true, will write files to staging/<timestamp>/
  const required = ['project_name'];
  const missing = required.filter(k => inputs[k] === undefined);
  if (missing.length) {
    return { status: 'failed', error: `Missing required inputs: ${missing.join(', ')}`, artifacts: [] };
  }

  const project = String(inputs.project_name);
  const writeAllowed = inputs.allow_write === true || inputs.allow_write === 'true';

  const stamp = nowStamp();
  const stagingRoot = path.join(__dirname, '..', '..', 'staging');
  const target = path.join(stagingRoot, `${project}-${stamp}`);

  const artifacts = [];
  const planSteps = [
    'Create staging folder',
    'Create backend (Express) scaffold: package.json, server.js, routes',
    'Create frontend (static) scaffold: index.html, src/App.js',
    'Create README explaining how to run the staging app'
  ];

  if (!writeAllowed) {
    artifacts.push(`Dry-run: would create staging at ${target}`);
    return { status: 'dry-run', artifacts, plan: { steps: planSteps } };
  }

  // ensure staging root exists
  try { fs.mkdirSync(stagingRoot, { recursive: true }); } catch (e) {}

  // create target folder
  try {
    fs.mkdirSync(target, { recursive: true });

    // backend files
    const backendDir = path.join(target, 'backend');
    fs.mkdirSync(backendDir);
    fs.writeFileSync(path.join(backendDir, 'package.json'), JSON.stringify({
      name: project.toLowerCase(),
      version: '0.1.0',
      main: 'server.js',
      scripts: { start: 'node server.js' }
    }, null, 2), 'utf8');

    fs.writeFileSync(path.join(backendDir, 'server.js'), `const express = require('express');\nconst app = express();\napp.use(express.json());\napp.get('/api/health', (req,res)=>res.json({ok:true}));\napp.get('/api/${project.toLowerCase()}', (req,res)=>res.json({data:[] }));\nconst port = process.env.PORT || 4000;\napp.listen(port, ()=>console.log('Backend running on', port));\n`, 'utf8');

    // frontend files (support lightweight static or Vite+React template)
    const frontendDir = path.join(target, 'frontend');
    fs.mkdirSync(frontendDir);
    const frontendTemplate = inputs.frontend_template || (inputs.include_frontend === true ? 'static' : (inputs.include_frontend || 'static'));

    if (frontendTemplate === 'vite' || String(frontendTemplate).toLowerCase() === 'vite') {
      // Vite + React minimal scaffold (no installs performed)
      fs.mkdirSync(path.join(frontendDir, 'src'));
      fs.writeFileSync(path.join(frontendDir, 'package.json'), JSON.stringify({
        name: `${project.toLowerCase()}-frontend`,
        private: true,
        scripts: { dev: 'vite', build: 'vite build', preview: 'vite preview' }
      }, null, 2), 'utf8');

      fs.writeFileSync(path.join(frontendDir, 'index.html'), `<!doctype html>\n<html><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width, initial-scale=1\"><title>${project}</title></head><body><div id=\"root\"></div><script type=\"module\" src=\"/src/main.jsx\"></script></body></html>`, 'utf8');

      fs.writeFileSync(path.join(frontendDir, 'src', 'main.jsx'), `import React from 'react';\nimport { createRoot } from 'react-dom/client';\nimport App from './App';\nconst root = createRoot(document.getElementById('root'))\nroot.render(React.createElement(App));\n`, 'utf8');

      fs.writeFileSync(path.join(frontendDir, 'src', 'App.jsx'), `import React from 'react';\nexport default function App(){ return React.createElement('div', null, '${project} (Vite + React) staging app'); }\n`, 'utf8');

      artifacts.push('frontend Vite+React scaffold (package.json, index.html, src/main.jsx, src/App.jsx) created');
    } else {
      fs.mkdirSync(path.join(frontendDir, 'src'));
      fs.writeFileSync(path.join(frontendDir, 'index.html'), `<!doctype html>\n<html><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width, initial-scale=1\"><title>${project}</title></head><body><div id=\"root\"></div><script src=\"src/App.js\"></script></body></html>`, 'utf8');
      fs.writeFileSync(path.join(frontendDir, 'src', 'App.js'), `console.log('Simple frontend for ${project}');\ndocument.getElementById('root').innerText = '${project} staging app';`, 'utf8');
      artifacts.push('frontend static scaffold (index.html, src/App.js) created');
    }

    // README
    const readme = `# ${project} (staging)\n\nThis staging scaffold was generated by the agent runtime.\n\nBackend: node (Express) - run:\n\n  cd backend; npm install; npm start\n\nFrontend: static files in frontend/ - open index.html or serve with a static server.\n`;
    fs.writeFileSync(path.join(target, 'README.md'), readme, 'utf8');

    artifacts.push(`Created staging folder at ${target}`);
    artifacts.push('backend/package.json and server.js created');
    artifacts.push('frontend/index.html and src/App.js created');

    return { status: 'success', artifacts, plan: { steps: planSteps }, staging_path: target };
  } catch (e) {
    return { status: 'error', error: String(e), artifacts: [] };
  }
};
